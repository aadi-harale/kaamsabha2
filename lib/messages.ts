/**
 * Worker-facing copy in English, Hindi and Marathi.
 *
 * Why a catalog rather than translated string fragments: these sentences carry numbers and
 * names, and Hindi and Marathi put the verb last and attach postpositions to the noun. Building
 * them by joining pieces — the way the English code used to — produces word salad in both. So
 * every message is a whole sentence with named placeholders, and each language writes its own
 * word order.
 *
 * Register: ordinary spoken Hindi and Marathi with respectful second person (आप / तुम्ही), not
 * Sanskritised officialese. The reader is a working member being told why they did or did not
 * get paid this week, and the wording should sound like a person, not a government form.
 *
 * Honest limitation: these translations have not been reviewed by a native speaker. They are
 * good-faith and grammatical, and they should be read by a Marathi and a Hindi speaker before
 * anyone relies on them in the field. See PRODUCTION_READINESS.md.
 *
 * Coverage is deliberate, not total. The member's own screens are translated — what they must
 * do next, why a job did or did not come to them, what a code means. Cooperative operations and
 * governance screens stay in English: they are record-first tools for an administrator, and a
 * half-translated audit trail is worse than an untranslated one.
 */

