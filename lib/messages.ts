const CATALOG: Record<Locale, Partial<Record<MessageKey, string>>> = { en: EN, hi: HI, mr: MR };

/**
 * Looks up one whole sentence and fills its placeholders.
 * A key missing from Hindi or Marathi falls back to English rather than rendering blank — a
 * partly translated screen is survivable, an empty one is not. A test asserts there are none.
 */
export function t(locale: Locale, key: MessageKey, params: MessageParams = {}): string {
  const template = CATALOG[locale]?.[key] ?? EN[key];
  return template.replace(/\{(\w+)\}/g, (whole, name: string) =>
    name in params ? String(params[name]) : whole,
  );
}

/** Keys a locale has not translated yet. Used by the tests and nothing else. */
export function missingKeys(locale: Locale): MessageKey[] {
  const catalog = CATALOG[locale] ?? {};
  return (Object.keys(EN) as MessageKey[]).filter((key) => !catalog[key]);
}

